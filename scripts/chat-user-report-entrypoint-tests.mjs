import assert from 'node:assert/strict';
import fs from 'node:fs';

const chat = fs.readFileSync('src/components/ChatConversation.tsx','utf8');
const seller = fs.readFileSync('src/components/SellerPublicProfile.tsx','utf8');
const reports = fs.readFileSync('src/services/onlineBackend.ts','utf8');
assert.match(chat, /const canReportUser = Boolean\(peerUid && user\.id && peerUid !== user\.id\)/);
const userStart = chat.indexOf('  const reportUser = async () => {');
const chatStart = chat.indexOf('  const reportChat = async () => {');
assert(userStart >= 0 && chatStart > userStart, 'user and conversation report must remain distinct actions');
const reportUser = chat.slice(userStart,chatStart);
assert.match(reportUser, /if \(!canReportUser \|\| reportUserBusy\) return/);
assert.match(reportUser, /await onlineBackend\.submitReport\('user', peerUid, reason\)/);
assert.match(reportUser, /reason\.trim\(\)\.length < 3/);
assert.match(reportUser, /useAppStore\.getState\(\)\.user\.id === reporterUid/);
assert.match(reportUser, /useAppStore\.getState\(\)\.activeChatId === chatId/);
assert.match(chat.slice(chatStart), /await onlineBackend\.submitReport\('chat', chatId, reason\)/);
const reportChat = chat.slice(chatStart, chat.indexOf('  const incomingSeverity', chatStart));
assert.match(reportChat, /if \(!user\.id \|\| reportChatPendingRef\.current\) return/);
assert.match(reportChat, /useAppStore\.getState\(\)\.user\.id === reporterUid/);
assert.match(reportChat, /useAppStore\.getState\(\)\.activeChatId === chatId/);
assert.match(reportChat, /if \(!sameReporterAndChat\(\)\) return/);
assert.match(reportChat, /reportChatPendingRef\.current = true/);
assert.match(reportChat, /reportChatPendingRef\.current = false/);
assert.match(reportChat, /if \(sameReporterAndChat\(\)\) setReportChatMessage\('Reporte de conversación enviado/);
assert.doesNotMatch(reportChat, /window\.alert/);
assert.match(chat, /disabled=\{reportChatBusy\}[^\n]*aria-label="Reportar conversación"/);
assert.match(chat, /role="status" aria-live="polite"[^\n]*reportChatMessage/);
// The child-safety reminder is always visible before quick messages and composition.
const reminder = chat.indexOf('aria-label="Recordatorio de seguridad para menores"');
const quick = chat.indexOf('quickMessages.map((message) =>');
assert(reminder >= 0 && quick > reminder, 'the safety reminder must appear before sending shortcuts');
assert.match(chat, /No acuerdes encuentros a solas con personas desconocidas/);
assert.match(chat, /canReportUser && <button[^\n]*onClick=\{\(\) => void reportUser\(\)\}/);
assert.match(chat, /aria-label="Reportar usuario"/);
assert.match(chat, /role="status" aria-live="polite"[^\n]*reportUserMessage/);
assert.match(seller, /onlineBackend\.submitReport\('user', sellerId, reason\)/);
assert.match(reports, /async submitReport\(targetType:/);
assert.match(reports, /nextReportRateBucket\(uid, at,/);
console.log('PASS chat exposes report-user separately from report-chat with authenticated peer and stale-UID response guard');
