import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

// A hermetic execution of the production write builders/loops. Do not import
// the reconciler: its top-level code can obtain Firebase access credentials.
const source = fs.readFileSync('scripts/reconcile-v2-reservations.mjs', 'utf8');
const helperStart = source.indexOf('function encodeValue(value) {');
const helperEnd = source.indexOf('async function requestJson(', helperStart);
const applyStart = source.indexOf('let applied = 0;');
const applyEnd = source.indexOf('console.log(', applyStart);
assert(helperStart >= 0 && helperEnd > helperStart && applyStart > helperEnd && applyEnd > applyStart, 'expected executable source sections');
const executable = '(async () => {\n' + source.slice(helperStart, helperEnd) + '\n'
  + source.slice(applyStart, applyEnd) + '\nreturn { applied, cleanedLocks };\n})()';
assert(!executable.includes('firebaseCiAccessToken'), 'fixture may not obtain credentials');
assert(!executable.includes('fetch('), 'fixture may not call network fetch');
assert(!executable.includes('spawnSync'), 'fixture may not spawn processes');

const projectId = 'tutop-synthetic-only';
const base = 'https://firestore.googleapis.com/v1/projects/' + projectId + '/databases/(default)/documents';
const T = '2026-11-02T22:10:00.000000Z';
const L = '2026-11-02T22:10:01.000000Z';
const K = '2026-11-02T22:10:02.000000Z';
const updatedAt = '2026-11-02T22:11:00.000Z';
const pathOf = (name) => {
  const prefix = 'projects/' + projectId + '/databases/(default)/documents/';
  assert(name.startsWith(prefix), 'outside synthetic project');
  return name.slice(prefix.length);
};

function initialState({ transactionStatus = 'reserved', listingStatus = 'active', availability = 'reserved', transactionTime = T, listingTime = L, lockTime = K } = {}) {
  return new Map([
    ['transactions_v2/tx-1', { version: transactionTime, fields: { status: transactionStatus } }],
    ['listings_v2/list-1', { version: listingTime, fields: { status: listingStatus, availability_status: availability } }],
    ['listing_reservation_locks/list-1', { version: lockTime, fields: { transaction_id: 'tx-1' } }],
  ]);
}
const snapshot = (state) => JSON.stringify([...state.entries()]);

async function execute(actionable, terminalLockPlans, state) {
  const commits = [];
  const requestJson = async (url, options) => {
    assert.equal(url, base + ':commit');
    assert.equal(options.method, 'POST');
    const writes = JSON.parse(options.body).writes;
    assert(Array.isArray(writes) && writes.length > 0 && writes.length <= 3);
    commits.push(writes);
    // Model Firestore transaction atomicity: check every precondition BEFORE
    // applying any changes. This verifies the writes generated by the real code.
    for (const write of writes) {
      // Firestore REST v1 Write only allows update/delete/transform.
      assert(!('verify' in write), 'Firestore REST Write cannot contain verify');
      assert(Object.keys(write).every(key => ['update', 'delete', 'transform', 'updateMask', 'currentDocument', 'updateTransforms'].includes(key)), 'unknown REST Write key');
      const fullName = write.update?.name ?? write.delete;
      assert(fullName, 'unknown REST Write operation');
      const record = state.get(pathOf(fullName));
      assert.equal(typeof write.currentDocument?.updateTime, 'string', 'every write must be version guarded');
      if (!record || record.version !== write.currentDocument.updateTime) {
        throw new Error('FAILED_PRECONDITION: stale snapshot');
      }
    }
    for (const write of writes) {
      if (write.delete) state.delete(pathOf(write.delete));
      else if (write.update) {
        const key = pathOf(write.update.name);
        const old = state.get(key);
        const fields = Object.fromEntries(Object.entries(write.update.fields)
          .map(([k, v]) => [k, v.stringValue ?? v.timestampValue ?? v.integerValue ?? v.booleanValue]));
        state.set(key, { version: updatedAt, fields: { ...old.fields, ...fields } });
      }
    }
    return {};
  };
  const output = vm.runInNewContext(executable, {
    projectId, base, actionable, terminalLockPlans, requestJson,
  }, { timeout: 1000 });
  return { output: await output, commits };
}
const expirePlan = { kind: 'expire_reserved', transaction_id: 'tx-1', listing_id: 'list-1',
  transaction_update_time: T, listing_update_time: L, lock_update_time: K };
const terminalPlan = (release_availability) => ({
  lock_id: 'list-1', listing_id: 'list-1', transaction_id: 'tx-1',
  transaction_status: release_availability ? 'expired' : 'completed',
  transaction_update_time: T, listing_update_time: L, lock_update_time: K,
  release_availability,
});

{
  const state = initialState();
  const result = await execute([expirePlan], [], state);
  assert.equal(result.output.applied, 1);
  assert.equal(result.output.cleanedLocks, 0);
  assert.equal(result.commits.length, 1, 'expiration must be one atomic commit');
  assert.equal(result.commits[0].length, 3);
  assert.equal(state.get('transactions_v2/tx-1').fields.status, 'expired');
  assert.equal(state.get('listings_v2/list-1').fields.availability_status, 'available');
  assert.equal(state.has('listing_reservation_locks/list-1'), false);
  console.log('PASS expiry atomicity: transaction, availability and lock');
}
{
  const state = initialState({ transactionStatus: 'completed', listingStatus: 'active' });
  const plan = { ...expirePlan, kind: 'repair_completed_listing' };
  const result = await execute([plan], [], state);
  assert.equal(result.commits.length, 1);
  assert.equal(result.commits[0].length, 3);
  assert(result.commits[0].some(w => w.update?.name.endsWith('/transactions_v2/tx-1')
    && w.update.fields.status.stringValue === 'completed'), 'bilateral completion transaction must be version checked with a legal status-preserving update');
  assert.equal(state.get('listings_v2/list-1').fields.status, 'sold_out');
  assert.equal(state.has('listing_reservation_locks/list-1'), false);
  console.log('PASS completed sale preserves signed transaction before sold_out repair');
}
{
  const state = initialState({ transactionStatus: 'expired' });
  const result = await execute([], [terminalPlan(true)], state);
  assert.equal(result.output.cleanedLocks, 1);
  assert.equal(result.commits[0].length, 3);
  assert.equal(state.get('listings_v2/list-1').fields.availability_status, 'available');
  assert.equal(state.has('listing_reservation_locks/list-1'), false);
  console.log('PASS already-terminal expired lock releases availability atomically');
}
{
  const state = initialState({ transactionStatus: 'completed', listingStatus: 'sold_out' });
  const result = await execute([], [terminalPlan(false)], state);
  assert.equal(result.output.cleanedLocks, 1);
  assert.equal(result.commits[0].length, 2);
  assert(result.commits[0].some(w => w.update?.name.endsWith('/transactions_v2/tx-1')
    && w.update.fields.status.stringValue === 'completed'), 'terminal completed cleanup must preserve verified transaction status');
  assert.equal(state.get('listings_v2/list-1').fields.availability_status, 'reserved');
  assert.equal(state.has('listing_reservation_locks/list-1'), false);
  console.log('PASS completed sold_out cleanup does not reopen listing');
}
for (const [kind, changed] of [
  ['stale transaction', { transactionTime: '2026-11-02T23:00:00.000000Z' }],
  ['stale listing', { listingTime: '2026-11-02T23:00:00.000000Z' }],
  ['replaced lock', { lockTime: '2026-11-02T23:00:00.000000Z' }],
]) {
  const state = initialState(changed);
  const original = snapshot(state);
  await assert.rejects(execute([expirePlan], [], state), /FAILED_PRECONDITION/);
  assert.equal(snapshot(state), original, 'stale commit may not partially mutate state');
  console.log('PASS rejected stale snapshot: ' + kind);
}
{
  const state = initialState({ lockTime: '2026-11-02T23:00:00.000000Z' });
  const original = snapshot(state);
  await assert.rejects(execute([], [terminalPlan(true)], state), /FAILED_PRECONDITION/);
  assert.equal(snapshot(state), original);
  console.log('PASS terminal cleanup rejects replaced lock');
}
{
  const state = initialState();
  const original = snapshot(state);
  await assert.rejects(execute([], [{ ...terminalPlan(true), transaction_status: undefined }], state), /TERMINAL_TRANSACTION_STATUS_INVALID/);
  assert.equal(snapshot(state), original);
  console.log('PASS missing terminal status is rejected before any write');
}
{
  const state = initialState();
  const result = await execute([{ kind: 'none' }], [], state);
  assert.equal(result.commits.length, 0);
  assert.equal(result.output.applied, 0);
  console.log('PASS no-op plan performs no writes');
}
